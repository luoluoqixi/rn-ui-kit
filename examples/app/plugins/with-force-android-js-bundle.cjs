const { withAppBuildGradle } = require("expo/config-plugins");

const marker = "// @generated by with-force-android-js-bundle";

const gradleConfig = `
${marker}
// Metro's inputs can live outside the Android project (for example, in a
// monorepo or node_modules), so Gradle cannot reliably detect every change.
// Always regenerate embedded JS bundles while retaining native build caches.
tasks.configureEach { task ->
    if (
        task.name.startsWith("createBundle") &&
        task.name.endsWith("JsAndAssets")
    ) {
        task.outputs.upToDateWhen { false }
    }
}
`;

module.exports = function withForceAndroidJsBundle(config) {
  return withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== "groovy") {
      throw new Error("with-force-android-js-bundle only supports Groovy build.gradle");
    }

    if (!config.modResults.contents.includes(marker)) {
      config.modResults.contents = `${config.modResults.contents.trimEnd()}\n${gradleConfig}`;
    }

    return config;
  });
};
