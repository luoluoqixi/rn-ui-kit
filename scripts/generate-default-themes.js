import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { semanticColorsToVariables } from "../src/core/components/ui/utils/theme/theme_variables";

import { accentThemeSeeds } from "../src/core/components/ui/utils/theme/accent_theme";
import { generateUiThemeFromPrimaryColor } from "../src/core/components/ui/utils/theme/generate_ui_theme";

const themes = Object.fromEntries(
  Object.entries(accentThemeSeeds).map(([name, seed]) => [name, generateUiThemeFromPrimaryColor(seed)]),
);
const output = `// Generated by scripts/generate-default-themes.js. Do not edit manually.\nimport type { UiThemeConfig } from "./ui_theme";\n\nexport const generatedAccentThemes = ${JSON.stringify(themes, null, 2)} satisfies Record<string, UiThemeConfig>;\n`;
const outputPath = fileURLToPath(
  new URL("../src/core/components/ui/utils/theme/default_accent_themes.ts", import.meta.url),
);

await writeFile(outputPath, output, "utf8");

// CSS fallback and JS themes come from the same source. Runtime preferences
// override these raw tokens through Uniwind, including document.body portals.
const declarations = (colors) => Object.entries(semanticColorsToVariables(colors))
  .map(([name, value]) => "      " + name + ": " + value + ";").join("\n");
const css = "/* Generated by scripts/generate-default-themes.js. Do not edit manually. */\n" +
  "@theme inline {\n" + Array.from({ length: 12 }, (_, index) => {
    const name = "accent" + String(index + 1).padStart(2, "0");
    return "  --color-" + name + ": var(--" + name + ");";
  }).join("\n") + "\n}\n\n@layer theme {\n  :root {\n" +
  "    @variant light {\n" + declarations(themes.ocean.light) + "\n    }\n" +
  "    @variant dark {\n" + declarations(themes.ocean.dark) + "\n    }\n  }\n}\n";
await writeFile(fileURLToPath(new URL("../src/theme.css", import.meta.url)), css, "utf8");
