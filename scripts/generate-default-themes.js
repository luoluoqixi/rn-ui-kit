import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { accentThemeSeeds } from "../src/core/components/ui/utils/theme/accent_theme";
import { generateUiThemeFromPrimaryColor } from "../src/core/components/ui/utils/theme/generate_ui_theme";

const themes = Object.fromEntries(
  Object.entries(accentThemeSeeds).map(([name, seed]) => [name, generateUiThemeFromPrimaryColor(seed)]),
);
const output = `// Generated by scripts/generate-default-themes.js. Do not edit manually.\nimport type { UiThemeConfig } from "./ui_theme";\n\nexport const generatedAccentThemes = ${JSON.stringify(themes, null, 2)} satisfies Record<string, UiThemeConfig>;\n`;
const outputPath = fileURLToPath(
  new URL("../src/core/components/ui/utils/theme/default_accent_themes.ts", import.meta.url),
);

await writeFile(outputPath, output, "utf8");
